-- =====================================================================
-- The Popsy Bar CRM: public.crm_inquiries
-- Safe to run more than once. It only CREATES things (never drops tables or data).
-- Requires public.is_admin() from supabase/schema.sql (run that first).
-- Run in: Supabase Dashboard -> SQL Editor -> New query -> paste -> Run.
-- =====================================================================

create table if not exists public.crm_inquiries (
  id uuid primary key default gen_random_uuid(),
  full_name text not null check (char_length(full_name) between 1 and 200),
  email text not null check (char_length(email) between 3 and 254),
  -- The date of the EVENT (chosen by the customer/admin). Not the same as created_at.
  event_date date,
  occasion_type text check (occasion_type is null or char_length(occasion_type) <= 120),
  guest_count integer check (guest_count is null or guest_count between 1 and 100000),
  event_description text not null default '' check (char_length(event_description) <= 5000),
  -- Assigned only by trusted server code: 'website' (public forms) or 'manual' (admin).
  source text not null check (source in ('website', 'manual')),
  -- Extra details some website forms collect.
  phone text check (phone is null or char_length(phone) <= 40),
  event_location text check (event_location is null or char_length(event_location) <= 200),
  extra jsonb not null default '{}'::jsonb,
  -- Random per-form-attempt token so a retried website submission can never create a second record.
  submission_token text unique check (submission_token is null or char_length(submission_token) <= 64),
  -- When the RECORD was created. Always generated by the database.
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Manual entries always carry the full set of CRM fields.
  constraint crm_manual_complete check (
    source <> 'manual'
    or (event_date is not null and occasion_type is not null and guest_count is not null)
  )
);

create index if not exists crm_inquiries_created_at_idx on public.crm_inquiries (created_at desc);
create index if not exists crm_inquiries_event_date_idx on public.crm_inquiries (event_date desc nulls last);
create index if not exists crm_inquiries_source_idx on public.crm_inquiries (source, created_at desc);
create index if not exists crm_inquiries_email_idx on public.crm_inquiries (lower(email));
create index if not exists crm_inquiries_name_idx on public.crm_inquiries (lower(full_name));

-- ---------------------------------------------------------------------
-- Integrity trigger: the database itself protects id, source, created_at and
-- submission_token, whatever any client sends.
-- ---------------------------------------------------------------------
create or replace function public.crm_inquiries_guard()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := now();
    new.updated_at := now();
  else
    new.id := old.id;
    new.source := old.source;
    new.created_at := old.created_at;
    new.submission_token := old.submission_token;
    new.updated_at := now();
  end if;
  return new;
end;
$$;

drop trigger if exists crm_inquiries_guard_trg on public.crm_inquiries;
create trigger crm_inquiries_guard_trg
  before insert or update on public.crm_inquiries
  for each row execute function public.crm_inquiries_guard();

-- ---------------------------------------------------------------------
-- Row Level Security: nobody but signed-in admins can touch this table.
-- There is deliberately NO anon policy and NO public insert policy.
-- Website submissions are written by the server with the service-role key
-- (which bypasses RLS) after validation; that key never reaches the browser.
-- ---------------------------------------------------------------------
alter table public.crm_inquiries enable row level security;

revoke all on public.crm_inquiries from anon;
revoke all on public.crm_inquiries from public;
grant select, insert, update, delete on public.crm_inquiries to authenticated;

drop policy if exists "admins read crm" on public.crm_inquiries;
create policy "admins read crm" on public.crm_inquiries
  for select to authenticated using (public.is_admin());

-- Admins may only ever insert rows whose source is 'manual'.
drop policy if exists "admins insert manual crm" on public.crm_inquiries;
create policy "admins insert manual crm" on public.crm_inquiries
  for insert to authenticated with check (public.is_admin() and source = 'manual');

drop policy if exists "admins update crm" on public.crm_inquiries;
create policy "admins update crm" on public.crm_inquiries
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins delete crm" on public.crm_inquiries;
create policy "admins delete crm" on public.crm_inquiries
  for delete to authenticated using (public.is_admin());
